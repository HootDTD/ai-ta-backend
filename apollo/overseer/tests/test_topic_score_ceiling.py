def test_ceiling_active_without_findings_never_docks():
    """``ceiling_active=True`` alone is inert: with nothing corroborated there
    is no finding to attribute a dock to, so a clean attempt is never capped."""
    nodes = [equation("eq.one", "One")]
    baseline = _score_of({"eq.one": 1.0}, nodes)
    assert baseline.score == 100
    assert _score_of({"eq.one": 1.0}, nodes, ceiling_active=True) == baseline
    assert _score_of({"eq.one": 1.0}, nodes, misconceptions={}, ceiling_active=True) == baseline


