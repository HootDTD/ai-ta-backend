def _case(name: str) -> dict[str, Any]:
    return dict(inertness_corpus())[name]


def _score_of(credits: dict[str, float], nodes: list, **kwargs: Any):
    """``compute_topic_score`` over an explicit per-node credit map."""
    return compute_topic_score(
        coverage={
            "per_step": {
                node.node_id: ("covered" if credits[node.node_id] >= 1.0 else "missing")
                for node in nodes
            },
            "procedure_scores": dict(credits),
        },
        reference_nodes=nodes,
        centrality=compute_centrality(KGGraph(nodes=nodes)),
        **kwargs,
    )


