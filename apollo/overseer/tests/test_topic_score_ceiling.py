def test_level3_shape_populates_misconceptions_without_moving_the_score():
    """LEVEL 3 (``ceiling_active=False``): ``topics[].misconceptions`` fills in
    with ``dock_points=0.0`` and the evidence span, while score, letter,
    coverage_component, misconception_dock and every topic's credit / status /
    weight stay exactly what the level-0 call produced."""
    nodes = [equation("eq.one", "One"), equation("eq.two", "Two")]
    credits = {"eq.one": 1.0, "eq.two": 1.0}
    baseline = _score_of(credits, nodes)
    level3 = _score_of(
        credits,
        nodes,
        misconceptions={"eq.one": _Finding("eq.one", "pressure rises with speed")},
    )

    assert level3.score == baseline.score
    assert level3.letter == baseline.letter
    assert level3.coverage_component == baseline.coverage_component
    assert level3.misconception_dock == baseline.misconception_dock == 0.0
    # The ONLY difference is the container.
    assert level3.topics[1] == baseline.topics[1]
    assert replace(level3.topics[0], misconceptions=()) == baseline.topics[0]
    (line,) = level3.topics[0].misconceptions
    assert line.canonical_key == "eq.one"
    assert line.resolved is False
    assert line.dock_points == 0.0
    assert line.evidence_span == "pressure rises with speed"


