def test_p1_ceiling_can_never_produce_a_d_or_an_f():
    """P-1: a ``min()`` cannot demote anyone into D or F. For every reachable
    raw score the ceilinged letter is D/F only when the raw letter already was,
    and above the ceiling the served letter is exactly B+."""
    for raw in range(0, 101):
        served = min(raw, CEILING_UNCORRECTED)
        if score_to_letter(served) in {"D", "F"}:
            assert score_to_letter(raw) in {"D", "F"}
        if raw > CEILING_UNCORRECTED:
            assert score_to_letter(served) == "B+"


def test_p1_holds_end_to_end_through_compute_topic_score():
    """The same property through the real scorer rather than the formula:
    sweeping one node's credit across the whole range with an uncorrected
    finding attached never lands a letter in a band the raw score wasn't in."""
    nodes = [equation("eq.one", "One"), equation("eq.two", "Two")]
    finding = {"eq.one": _Finding("eq.one", "reversed the sign")}
    for step in range(0, 101):
        credits = {"eq.one": step / 100, "eq.two": 1.0}
        raw = _score_of(credits, nodes)
        served = _score_of(credits, nodes, misconceptions=finding, ceiling_active=True)
        assert served.score == min(raw.score, CEILING_UNCORRECTED)
        if served.letter in {"D", "F"}:
            assert raw.letter in {"D", "F"}


def test_p2_ceiling_applied_once_not_repeated_subtraction():
    """P-2: one ``min()``, never a per-finding subtraction. Three uncorrected
    findings cap at the same 84 as one, the dock is ``raw - 84`` once, and the
    call is idempotent."""
    nodes = [equation("eq.one", "One"), equation("eq.two", "Two"), equation("eq.three", "Three")]
    credits = {"eq.one": 1.0, "eq.two": 1.0, "eq.three": 1.0}
    assert _score_of(credits, nodes).score == 100

    def _with(node_ids: tuple[str, ...]):
        return _score_of(
            credits,
            nodes,
            misconceptions={node_id: _Finding(node_id, "a") for node_id in node_ids},
            ceiling_active=True,
        )

    one = _with(("eq.one",))
    three = _with(("eq.one", "eq.two", "eq.three"))
    assert one.score == three.score == CEILING_UNCORRECTED
    assert one.misconception_dock == three.misconception_dock == 16.0
    assert three == _with(("eq.one", "eq.two", "eq.three"))


def test_p2_score_at_or_below_the_ceiling_is_never_touched():
    """The other half of P-2: the ceiling only binds above 84 — an attempt
    already at or under it keeps its exact score and takes a zero dock."""
    nodes = [equation("eq.one", "One"), equation("eq.two", "Two")]
    credits = {"eq.one": 0.6, "eq.two": 1.0}
    raw = _score_of(credits, nodes)
    assert raw.score <= CEILING_UNCORRECTED
    served = _score_of(
        credits, nodes, misconceptions={"eq.one": _Finding("eq.one", "a")}, ceiling_active=True
    )
    assert served.score == raw.score
    assert served.letter == raw.letter
    assert served.misconception_dock == 0.0
    assert served.topics[0].misconceptions[0].dock_points == 0.0


def test_p3_no_double_jeopardy_with_interaction5_aside_cap():
    """P-3: INTERACTION5's flat 0.5 aside cap and the ceiling can never stack.
    A Hoot-assisted node is capped at 0.5, strictly below the 0.6 credit gate
    S2' requires, so such a node can never carry a corroborated finding in the
    first place — the two levers are disjoint by arithmetic, not by policy."""
    nodes = [equation("eq.one", "One"), equation("eq.two", "Two")]
    capped, assisted = apply_aside_caps(
        {
            "per_step": {"eq.one": "covered", "eq.two": "covered"},
            "procedure_scores": {"eq.one": 1.0, "eq.two": 1.0},
            "hoot_assisted": {"eq.one": True, "eq.two": False},
        }
    )
    assert assisted == ("eq.one",)
    result = compute_topic_score(
        coverage=capped,
        reference_nodes=nodes,
        centrality=compute_centrality(KGGraph(nodes=nodes)),
    )
    assisted_topic = {topic.canonical_key: topic for topic in result.topics}["eq.one"]
    assert assisted_topic.credit == 0.5
    # THE disjointness: the capped credit is below the S2' corroboration gate,
    # which is numerically the same 0.6 this module already keys two other
    # decisions on. If that constant moves, this assertion moves with it.
    assert assisted_topic.credit < UNPROBED_CREDIT_KEEP_THRESHOLD == 0.6
    assert UNPROBED_CREDIT_KEEP_THRESHOLD == REFERENCE_TEXT_CREDIT_THRESHOLD


def test_dock_points_sum_exactly_to_misconception_dock():
    """Largest-remainder allocation: the per-finding lines sum to the attempt
    dock EXACTLY (integer points, so no float drift can reach a teacher) and the
    residual lands on the earliest finding in reference order."""
    nodes = [equation(f"eq.{index}", str(index)) for index in range(3)]
    credits = {node.node_id: 1.0 for node in nodes}
    result = _score_of(
        credits,
        nodes,
        misconceptions={node.node_id: _Finding(node.node_id, "a") for node in nodes},
        ceiling_active=True,
    )

    lines = [misc for topic in result.topics for misc in topic.misconceptions]
    assert sum(line.dock_points for line in lines) == result.misconception_dock == 16.0
    # 16 points over 3 findings -> 6/5/5, extra point first, deterministic.
    assert [line.dock_points for line in lines] == [6.0, 5.0, 5.0]


def test_resolved_findings_never_ceiling_and_never_carry_dock_points():
    """Decision D7: the ceiling is suppressed on resolution. A student who
    corrected the claim is reported, never capped."""
    nodes = [equation("eq.one", "One")]
    result = _score_of(
        {"eq.one": 1.0},
        nodes,
        misconceptions={"eq.one": _Finding("eq.one", "I was wrong", resolved=True)},
        ceiling_active=True,
    )
    assert result.score == 100
    assert result.misconception_dock == 0.0
    assert result.topics[0].misconceptions[0].resolved is True
    assert result.topics[0].misconceptions[0].dock_points == 0.0


def test_only_uncorrected_findings_share_the_dock():
    nodes = [equation("eq.one", "One"), equation("eq.two", "Two")]
    result = _score_of(
        {"eq.one": 1.0, "eq.two": 1.0},
        nodes,
        misconceptions={
            "eq.one": _Finding("eq.one", "fixed it", resolved=True),
            "eq.two": _Finding("eq.two", "still wrong"),
        },
        ceiling_active=True,
    )
    by_key = {topic.canonical_key: topic for topic in result.topics}
    assert by_key["eq.one"].misconceptions[0].dock_points == 0.0
    assert by_key["eq.two"].misconceptions[0].dock_points == 16.0
    assert result.misconception_dock == 16.0


def test_finding_for_an_unknown_node_is_ignored_and_never_ceilings():
    """A finding whose node is not part of this grade cannot be attributed, so
    it must never silently cap the attempt (fail-safe = miss)."""
    nodes = [equation("eq.one", "One")]
    result = _score_of(
        {"eq.one": 1.0},
        nodes,
        misconceptions={"ghost": _Finding("ghost", "a")},
        ceiling_active=True,
    )
    assert result.score == 100
    assert result.misconception_dock == 0.0
    assert all(topic.misconceptions == () for topic in result.topics)


